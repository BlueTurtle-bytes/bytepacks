package build

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/apexpack/apexpack/internal/types"
)

// emitProbesYAML writes a probes.yaml snippet to the output directory.
// The file contains ready-to-paste Kubernetes liveness/readiness/startupProbe
// config derived from the health check configuration. It is always written
// alongside the image, regardless of whether the build is local or published.
func emitProbesYAML(opts Options, hc *types.HealthCheckConfig) {
	if hc == nil || hc.Disabled {
		return
	}

	interval := durationSecs(hc.Interval, 30)
	timeout := durationSecs(hc.Timeout, 5)
	startPeriod := durationSecs(hc.StartPeriod, 10)
	retries := hc.Retries
	if retries == 0 {
		retries = 3
	}

	var sb strings.Builder
	sb.WriteString("# Generated by apexpack\n")
	sb.WriteString("# Paste into your Kubernetes Deployment under spec.template.spec.containers[*]\n")

	switch {
	case hc.HTTP != nil:
		port := hc.HTTP.Port
		if port == 0 {
			port = 8080
		}
		path := hc.HTTP.Path
		if path == "" {
			path = "/"
		}
		writeHTTPProbes(&sb, path, port, interval, timeout, startPeriod, retries)
	case hc.TCP != nil:
		writeTCPProbes(&sb, hc.TCP.Port, interval, timeout, startPeriod, retries)
	default:
		return
	}

	outPath := filepath.Join(opts.OutputDir, "probes.yaml")
	if err := os.WriteFile(outPath, []byte(sb.String()), 0o644); err != nil {
		fmt.Printf("  → WARN: could not write probes.yaml: %v\n", err)
		return
	}
	fmt.Printf("  → wrote %s\n", outPath)
}

func writeHTTPProbes(sb *strings.Builder, path string, port, interval, timeout, startPeriod, retries int) {
	probe := func(name string, period, timeoutSecs, failureThreshold int, initialDelay ...int) {
		fmt.Fprintf(sb, "%s:\n", name)
		fmt.Fprintf(sb, "  httpGet:\n")
		fmt.Fprintf(sb, "    path: %s\n", path)
		fmt.Fprintf(sb, "    port: %d\n", port)
		if len(initialDelay) > 0 && initialDelay[0] > 0 {
			fmt.Fprintf(sb, "  initialDelaySeconds: %d\n", initialDelay[0])
		}
		fmt.Fprintf(sb, "  periodSeconds: %d\n", period)
		fmt.Fprintf(sb, "  timeoutSeconds: %d\n", timeoutSecs)
		fmt.Fprintf(sb, "  failureThreshold: %d\n", failureThreshold)
	}

	probe("livenessProbe", interval, timeout, retries)
	probe("readinessProbe", interval, timeout, retries)
	// startupProbe: allow up to startPeriod * 6 seconds for slow-starting apps.
	probe("startupProbe", 10, timeout, startPeriod/10*6+6, startPeriod)
}

func writeTCPProbes(sb *strings.Builder, port, interval, timeout, startPeriod, retries int) {
	probe := func(name string, period, timeoutSecs, failureThreshold int, initialDelay ...int) {
		fmt.Fprintf(sb, "%s:\n", name)
		fmt.Fprintf(sb, "  tcpSocket:\n")
		fmt.Fprintf(sb, "    port: %d\n", port)
		if len(initialDelay) > 0 && initialDelay[0] > 0 {
			fmt.Fprintf(sb, "  initialDelaySeconds: %d\n", initialDelay[0])
		}
		fmt.Fprintf(sb, "  periodSeconds: %d\n", period)
		fmt.Fprintf(sb, "  timeoutSeconds: %d\n", timeoutSecs)
		fmt.Fprintf(sb, "  failureThreshold: %d\n", failureThreshold)
	}

	probe("livenessProbe", interval, timeout, retries)
	probe("readinessProbe", interval, timeout, retries)
	probe("startupProbe", 10, timeout, startPeriod/10*6+6, startPeriod)
}

// durationSecs parses a duration string (e.g. "30s") and returns seconds.
// Returns defaultVal when the string is empty or unparseable.
func durationSecs(s string, defaultVal int) int {
	if s == "" {
		return defaultVal
	}
	d, err := time.ParseDuration(s)
	if err != nil || d <= 0 {
		return defaultVal
	}
	return int(d.Seconds())
}
